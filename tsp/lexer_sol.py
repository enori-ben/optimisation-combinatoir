import ply.lex as lex

# =========================================================
# Token list
# =========================================================
tokens = (
    "INSTANCE_NAME",
    "COLON",
    "NUMBER",
)

# =========================================================
# Instance name
# (simplified + safer version)
# =========================================================
def t_INSTANCE_NAME(t):
    r"[A-Za-z_][A-Za-z0-9_]*"
    return t

# =========================================================
# Numbers
# =========================================================
def t_NUMBER(t):
    r"\d+"
    t.value = int(t.value)
    return t

# =========================================================
# Symbols
# =========================================================
t_COLON = r":"

# =========================================================
# Ignored characters
# =========================================================
t_ignore = " \t\r\n"

# =========================================================
# Error handling
# =========================================================
def t_error(t):
    print(f"[Lexer Error] Illegal character '{t.value[0]}' at position {t.lexpos}")
    t.lexer.skip(1)

