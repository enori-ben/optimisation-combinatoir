import ply.lex as lex

# =========================================================
# TOKENS
# =========================================================
tokens = (
    "NAME",
    "DIMENSION",
    "NUMBER",
    "SECTION",
)

# =========================================================
# NAME (e.g., NAME: kroA100)
# =========================================================
def t_NAME(t):
    r"NAME\s*:\s*\S+"
    t.value = t.value.split(":", 1)[1].strip()
    return t

# =========================================================
# DIMENSION (we only detect keyword, not value here)
# =========================================================
def t_DIMENSION(t):
    r"DIMENSION\s*:"
    return t

# =========================================================
# SECTION HEADERS
# =========================================================
def t_SECTION(t):
    r"NODE_COORD_SECTION|DISPLAY_DATA_SECTION"
    return t

# =========================================================
# NUMBERS (safe, simple)
# =========================================================
def t_NUMBER(t):
    r"[+-]?\d+(\.\d+)?([eE][+-]?\d+)?"
    t.value = float(t.value)
    return t

# =========================================================
# NEWLINES
# =========================================================
def t_newline(t):
    r"\n+"
    t.lexer.lineno += len(t.value)

# =========================================================
# IGNORE SPACES/TABS
# =========================================================
t_ignore = " \t"

# =========================================================
# ERROR HANDLING
# =========================================================
def t_error(t):
    print(f"[Lexer Error] Illegal char '{t.value[0]}' at line {t.lineno}")
    t.lexer.skip(1)

# =========================================================
# BUILD LEXER
# =========================================================
lexer = lex.lex()